#!/bin/bash
# builds the SPU program and turns it into a C array linked into libws.a
set -e
cd /home/claude/w/wsps3/spu
. ../FLAGS.sh
spu-gcc -O3 -Wall -fno-strict-aliasing -I$PSL1GHT/spu/include -c spu_gpu_main.c -o spu_gpu_main.o
spu-gcc -O3 spu_gpu_main.o -L$PSL1GHT/spu/lib -lsputhread -o spu_gpu.elf
python3 - <<'P'
d=open('spu_gpu.elf','rb').read()
out=['/* generated by spu/build_spu.sh */','const unsigned char ws_spu_gpu_elf[] __attribute__((aligned(128))) = {']
for i in range(0,len(d),16): out.append(','.join(str(b) for b in d[i:i+16])+',')
out.append('};'); out.append('const unsigned ws_spu_gpu_elf_size = %d;'%len(d))
open('../spu_bin.c','w').write('\n'.join(out)+'\n')
P
ls -la spu_gpu.elf
