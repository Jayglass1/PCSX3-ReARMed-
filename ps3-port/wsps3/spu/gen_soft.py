#!/usr/bin/env python3
"""Extract the PEOPS polygon rasterizer pieces from SoftGPU/soft.c for the SPU build.
The code is copied verbatim (so geometry and rounding stay identical); only these edits are made:
  - FASTSOLID blocks are dropped (generic loops give the same result)
  - psxVub[x] / psxVuw[x] texture reads go through TEXB()/TEXW() (software-cached on the SPU)
"""
import re, sys
src = [l for l in open('../SoftGPU/soft.c').read().split('\n') if not l.startswith(' if(spu_cap)')]

def find_func(name):
    pat = re.compile(r'^(static\s+)?(inline\s+)?[A-Za-z_][\w\s\*]*\b' + re.escape(name) + r'\s*\(')
    for i, l in enumerate(src):
        if pat.match(l) and not l.rstrip().endswith(';'):
            return i
    raise SystemExit('function not found: ' + name)

def extract(name):
    i = find_func(name)
    # advance to opening brace
    depth = 0; started = False; j = i
    while True:
        l = src[j]
        l2 = re.sub(r'//.*', '', l)
        l2 = re.sub(r'/\*.*?\*/', '', l2)
        for ch in l2:
            if ch == '{': depth += 1; started = True
            elif ch == '}': depth -= 1
        if started and depth == 0: break
        j += 1
    return '\n'.join(src[i:j+1])

def drop_fastsolid(text):
    out = []; skip = 0; stack = []
    for l in text.split('\n'):
        s = l.strip()
        if s.startswith('#ifdef FASTSOLID'):
            skip = 1; continue
        if skip:
            if s.startswith('#if'): skip += 1
            elif s.startswith('#endif'):
                skip -= 1
            continue
        out.append(l)
    return '\n'.join(out)

def bracket(text, key, repl_open):
    """replace key[expr] with repl_open expr ) for balanced brackets"""
    out = []; i = 0
    while True:
        k = text.find(key + '[', i)
        if k < 0: out.append(text[i:]); break
        out.append(text[i:k])
        j = k + len(key) + 1; d = 1
        while d:
            if text[j] == '[': d += 1
            elif text[j] == ']': d -= 1
            j += 1
        expr = text[k + len(key) + 1:j - 1]
        out.append(repl_open + '(' + expr + ')')
        i = j
    return ''.join(out)

def tex(text):
    # GETLE16(&psxVuw[x]) -> TEXW(x)   (TEXW already returns the decoded value)
    text = re.sub(r'GETLE16\(&psxVuw\[', 'TEXW_ADDR_BEGIN[', text)
    text = bracket(text, 'TEXW_ADDR_BEGIN', 'TEXW_ADDR_TMP')
    text = text.replace('TEXW_ADDR_TMP(', 'TEXW(')
    # the matching ')' of GETLE16( remains: TEXW(x)) -> need to drop one ')'
    return text

parts = []
funcs_color = ['Dither16', 'GetShadeTransCol_Dither', 'GetShadeTransCol', 'GetShadeTransCol32', 'GetTextureTransColG32',
               'GetTextureTransColG', 'GetTextureTransColGX_Dither', 'GetTextureTransColGX', 'GetTextureTransColGX32_S', 'GetTextureTransColGX_S']
funcs_geom = ['shl10idiv']
for pre in ['F', 'G', 'FT', 'GT', 'F4', 'FT4', 'GT4']:
    funcs_geom += ['RightSection_' + pre, 'LeftSection_' + pre, 'NextRow_' + pre, 'SetupSections_' + pre]
funcs_poly = ['drawPoly3Fi', 'drawPoly4F', 'drawPoly3Gi',
              'drawPoly3TEx4', 'drawPoly4TEx4', 'drawPoly3TEx8', 'drawPoly4TEx8', 'drawPoly3TD', 'drawPoly4TD',
              'drawPoly3TGEx4', 'drawPoly4TGEx4', 'drawPoly3TGEx8', 'drawPoly4TGEx8', 'drawPoly3TGD', 'drawPoly4TGD']

out = ['/* generated by gen_soft.py from SoftGPU/soft.c -- do not edit */']
a = next(i for i, l in enumerate(src) if l.startswith('typedef struct SOFTVTAG'))
b = next(i for i, l in enumerate(src) if l.startswith('static int left_B'))
out.append('\n'.join(src[a:b+1]))
for f in funcs_color + funcs_geom + funcs_poly:
    t = extract(f)
    if not (f.startswith('drawPoly') and 'TG' in f): t = drop_fastsolid(t)
    out.append(t)
text = '\n\n'.join(out)

# texture reads
def conv_reads(text):
    # psxVuw word reads wrapped in GETLE16(&psxVuw[...]) -> TEXW(...)
    res = []; i = 0
    key = 'GETLE16(&psxVuw['
    while True:
        k = text.find(key, i)
        if k < 0: res.append(text[i:]); break
        res.append(text[i:k])
        j = k + len(key); d = 1
        while d:
            c = text[j]
            if c == '[': d += 1
            elif c == ']': d -= 1
            j += 1
        expr = text[k + len(key):j - 1]
        assert text[j] == ')', text[j-20:j+20]
        res.append('TEXW(' + expr + ')')
        i = j + 1
    text = ''.join(res)
    text = bracket(text, 'psxVub', 'TEXB')
    text = text.replace(' unsigned char *src;\n','').replace(' src = &TEXB(YAdjust);\n','')
    text = bracket(text, 'src', 'TEXB_SRC')
    text = bracket(text, 'psxVuw', 'TEXW_RAW')
    return text
text = conv_reads(text)
open('spu_soft_gen.inc', 'w').write(text + '\n')
print('wrote spu_soft_gen.inc', len(text), 'bytes')
for bad in ['psxVuw', 'psxVub', 'FASTSOLID']:
    print(bad, text.count(bad))
print('TEXW_RAW uses:', text.count('TEXW_RAW'))
